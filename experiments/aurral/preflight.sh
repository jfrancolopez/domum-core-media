#!/usr/bin/env bash
# Pre-deployment check for the Aurral experiment: the saved rulesets are
# usable, and the live ruleset still matches them.
#
# EXIT STATUS IS THE CONTRACT, so a caller can act on it without parsing prose:
#
#   0  match        both families identical to their backup -- no Aurral rules
#                   present. This is the state in which it is safe to apply.
#   3  aurral-only  the ONLY differences are Aurral's own rules, every one of
#                   them scoped to the aurral0 bridge. Expected AFTER `apply`;
#                   not a defect, and deliberately not 0, because "already
#                   applied" and "nothing applied" are different facts.
#   4  order-only  the non-Aurral differences are the SAME rules in a different
#                   ORDER -- nothing added, nothing removed. Docker re-emits its
#                   per-container PREROUTING guards in container-start order, so
#                   recreating the stack shuffles them. Safe to apply; kept
#                   non-zero and printed, because within a chain order IS
#                   semantics in general and this must not read as MATCH.
#   1  drift        something that is neither a counter nor Aurral's differs.
#                   A REMOVED production rule lands here, which is the case
#                   that matters most.
#   2  cannot answer -- a backup is missing, empty or unreadable, or the live
#                   ruleset could not be read. Never reported as either verdict:
#                   "I could not check it" is not "it is clean" and not "it is
#                   broken" either.
#
# Read-only. It never applies, flushes, restores or removes anything.
set -euo pipefail

die()  { printf 'preflight: %s\n' "$*" >&2; exit 2; }
# STDERR, not stdout: classify_family's stdout IS its return value, so a log
# line written there comes back glued to the verdict word. Measured -- the first
# version did exactly that and `case "$v4 $v6"` fell through to the wrong arm.
note() { printf '  %s\n' "$*" >&2; }

V4_BACKUP="${1:-/root/iptables-before-aurral.txt}"
V6_BACKUP="${2:-/root/ip6tables-before-aurral.txt}"

# Overridable so the classifier can be driven without root -- reading the live
# ruleset is the only privileged step, and without a seam here the whole script
# would be untestable and its branches would never be exercised. Both default
# to the real savers, so production behaviour is unchanged by their existence.
V4_LIVE="${AURRAL_PREFLIGHT_V4_LIVE:-}"
V6_LIVE="${AURRAL_PREFLIGHT_V6_LIVE:-}"

TMP="$(mktemp -d)"
cleanup() { rm -rf "$TMP"; }
trap cleanup EXIT

# `iptables-save` ALWAYS emits the chain-policy counters in its
# ":CHAIN POLICY [pkts:bytes]" lines. `-c` adds per-RULE counters on top; it is
# not what introduces these. On a host passing traffic those counters advance
# every second, so a byte-for-byte comparison against a saved file can NEVER
# match -- it reports a difference 100% of the time, including against a
# pristine ruleset, which makes it a gate that only ever says STOP. Measured on
# this host 2026-11-24: the first comparison written for this procedure did
# exactly that, and the saved file itself carries
# ":PREROUTING ACCEPT [40003:5236053]".
#
# So the counters are zeroed and the "# Generated by ... on <date>" header is
# dropped, and what gets compared is the RULES.
normalise_ruleset() {
  sed -E -e '/^#/d' \
         -e 's/^(:[A-Za-z0-9_.+-]+ (ACCEPT|DROP|REJECT|QUEUE|RETURN|-)) \[[0-9]+:[0-9]+\]$/\1 [0:0]/'
}

# Aurral's rules are recognised by the bridge they are scoped to and by the two
# chain names. Every rule the policy installs carries one or the other, which is
# also the property that makes the policy auditable at all: a rule of Aurral's
# that mentioned neither would be indistinguishable from drift, and would be
# reported as drift rather than quietly accepted.
AURRAL_RE='aurral0|AURRAL-'

read_live() {
  local family="$1" override="$2" out="$3"
  if [[ -n "$override" ]]; then
    [[ -r "$override" ]] || die "cannot read the injected live ruleset: $override"
    normalise_ruleset <"$override" >"$out"
    return 0
  fi
  local saver="iptables-save"
  [[ "$family" == v6 ]] && saver="ip6tables-save"
  command -v "$saver" >/dev/null 2>&1 || die "$saver not found"
  [[ "$(id -u)" -eq 0 ]] || die "reading the live $family ruleset needs root (use sudo)"
  # The failure is expected and handled, so the status is captured rather than
  # left to abort the script under errexit.
  local rc=0
  "$saver" 2>"$TMP/$family.err" | normalise_ruleset >"$out" || rc=$?
  if (( rc != 0 )) || [[ ! -s "$out" ]]; then
    die "$saver failed: $(sed -n '1p' "$TMP/$family.err" 2>/dev/null || echo 'no diagnostic was produced')"
  fi
}

# Prints the verdict word; the caller maps it to an exit status.
classify_family() {
  local family="$1" backup="$2" override="$3"
  [[ -e "$backup" ]] || { note "$family: CANNOT ANSWER -- backup does not exist: $backup"; printf 'cannot-answer'; return 0; }
  [[ -s "$backup" ]] || { note "$family: CANNOT ANSWER -- backup is EMPTY: $backup"; printf 'cannot-answer'; return 0; }
  [[ -r "$backup" ]] || { note "$family: CANNOT ANSWER -- backup is unreadable: $backup"; printf 'cannot-answer'; return 0; }

  normalise_ruleset <"$backup" >"$TMP/$family.backup"
  read_live "$family" "$override" "$TMP/$family.live"

  local d="$TMP/$family.diff"
  diff --unchanged-line-format='' --old-line-format='-%L' --new-line-format='+%L' \
       "$TMP/$family.backup" "$TMP/$family.live" >"$d" || true

  local add rem a_add a_rem o_add o_rem
  add="$(grep -c '^+' "$d" || true)";  rem="$(grep -c '^-' "$d" || true)"
  a_add="$(grep '^+' "$d" | grep -cE "$AURRAL_RE" || true)"
  a_rem="$(grep '^-' "$d" | grep -cE "$AURRAL_RE" || true)"
  o_add=$(( add - a_add )); o_rem=$(( rem - a_rem ))

  note "$family: backup $(grep -c . "$TMP/$family.backup") rule lines, live $(grep -c . "$TMP/$family.live")"
  note "$family: additions $add (Aurral $a_add, other $o_add); removals $rem (Aurral $a_rem, other $o_rem)"

  if (( o_add == 0 && o_rem == 0 )); then
    if (( a_add == 0 && a_rem == 0 )); then
      note "$family: MATCH -- identical to the backup once counters are normalised"
      printf 'match'
    else
      note "$family: AURRAL-ONLY -- the only differences are Aurral's $a_add rule(s), all scoped to aurral0"
      printf 'aurral-only'
    fi
  else
    # A REORDERING is not a rule change, and conflating them sends the operator
    # hunting for a lost production rule that is still there. Docker emits one
    # PREROUTING guard per container and re-emits them in container-start order,
    # so recreating the stack shuffles them -- measured 2026-11-25: 9 "removals"
    # and 9 "additions" that were the SAME nine rules, every IP belonging to a
    # live container. Reported as its own verdict, never folded into MATCH:
    # within a chain order IS semantics in general, so this stays non-zero and
    # prints the rules.
    grep '^+' "$d" | grep -vE "$AURRAL_RE" | sed 's/^+//' | sort >"$TMP/$family.oadd" || true
    grep '^-' "$d" | grep -vE "$AURRAL_RE" | sed 's/^-//' | sort >"$TMP/$family.orem" || true
    if (( o_add > 0 && o_add == o_rem )) && cmp -s "$TMP/$family.oadd" "$TMP/$family.orem"; then
      note "$family: ORDER-ONLY -- the $o_add non-Aurral difference(s) are the SAME"
      note "$family: rules in a different ORDER. Nothing was added or removed."
      sed -n '1,40{s/^/      /;p;}' "$TMP/$family.oadd" >&2
      printf 'order-only'
    else
      note "$family: DRIFT -- $o_add addition(s) and $o_rem removal(s) are NOT Aurral's:"
      grep -E '^[+-]' "$d" | grep -vE "$AURRAL_RE" | sed -n '1,40{s/^/      /;p;}' >&2
      printf 'drift'
    fi
  fi
}

printf '== Aurral preflight: saved rulesets vs live\n'
v4="$(classify_family v4 "$V4_BACKUP" "$V4_LIVE")"
v6="$(classify_family v6 "$V6_BACKUP" "$V6_LIVE")"
printf '== verdict: v4=%s v6=%s\n' "$v4" "$v6"

# The WEAKEST verdict governs, so one family being clean can never mask the
# other -- the same rule `storage scrub` follows across filesystems.
case "$v4 $v6" in
  *cannot-answer*) printf 'CANNOT ANSWER -- do not treat this as a pass.\n'; exit 2 ;;
  *drift*)         printf 'DRIFT -- a non-Aurral rule changed. STOP and investigate.\n'; exit 1 ;;
  *order-only*)    printf 'ORDER-ONLY -- same rules, different order (a container restart does\n'
                   printf 'this). No production rule was added or removed. Safe to apply.\n'; exit 4 ;;
  "match match")   printf 'MATCH -- no Aurral rules present; safe to apply the policy.\n'; exit 0 ;;
  *)               printf 'AURRAL-ONLY -- the policy is applied and nothing else changed.\n'; exit 3 ;;
esac
