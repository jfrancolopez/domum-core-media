#!/usr/bin/env bash
# Drives experiments/aurral/preflight.sh end to end, without root, through the
# injected-live-ruleset seam.
#
# The load-bearing case is section 1. The first version of this comparison,
# written straight into an operator block, compared the saved ruleset to the
# live one byte for byte -- and `iptables-save` always emits chain-policy
# counters, so on a host passing traffic it reported DRIFT 100% of the time.
# It was a gate that could only ever say STOP, and it said STOP on a pristine
# ruleset. A test that only drove the drift case would have passed against it.
set -uo pipefail

PF="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/experiments/aurral/preflight.sh"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
fails=0; n=0
ok()   { n=$((n+1)); printf '  ok    %s\n' "$*"; }
bad()  { n=$((n+1)); fails=$((fails+1)); printf '  FAIL  %s\n' "$*"; }
sect() { printf '\n== %s\n' "$*"; }

# A ruleset shaped like this host's: counters on the policy lines, a ts-input
# jump, an empty DOCKER-USER.
ruleset() { # $1 = counter seed, $2 = extra filter rules (may be empty)
  local c="$1" extra="${2:-}"
  printf '# Generated by iptables-save v1.8.11 on %s\n' "$(date -Is)"
  printf '*mangle\n:PREROUTING ACCEPT [%s:%s0]\n:INPUT ACCEPT [0:0]\nCOMMIT\n' "$c" "$c"
  printf '*filter\n:INPUT ACCEPT [%s:%s0]\n:FORWARD DROP [0:0]\n:DOCKER-USER - [0:0]\n:ts-input - [0:0]\n' "$c" "$c"
  [[ -n "$extra" ]] && printf '%s\n' "$extra"
  printf -- '-A INPUT -j ts-input\n-A FORWARD -j DOCKER-USER\n-A ts-input -i lo -j ACCEPT\nCOMMIT\n'
}
AURRAL_RULES='-A INPUT -i aurral0 -j AURRAL-HOST
-A AURRAL-EGRESS -o aurral0 -j RETURN
-A AURRAL-EGRESS -d 198.51.100.0/24 -j DROP
-A AURRAL-HOST -j DROP
-A DOCKER-USER -i aurral0 -j AURRAL-EGRESS'

run() { # $1 v4 backup, $2 v4 live, $3 v6 backup, $4 v6 live -> prints rc then output
  AURRAL_PREFLIGHT_V4_LIVE="$2" AURRAL_PREFLIGHT_V6_LIVE="$4" \
    bash "$PF" "$1" "$3" >"$TMP/out" 2>&1
  printf '%s' "$?"
}

ruleset 1000 > "$TMP/backup4"; ruleset 1000 > "$TMP/backup6"

sect "1. COUNTERS ONLY -- must be MATCH (exit 0). The original check said DRIFT here."
ruleset 999999 > "$TMP/live4"; ruleset 888888 > "$TMP/live6"
rc="$(run "$TMP/backup4" "$TMP/live4" "$TMP/backup6" "$TMP/live6")"
[[ "$rc" == 0 ]] && ok "counter-only difference => exit 0" || bad "counter-only gave exit $rc, expected 0"
grep -q 'v4=match v6=match' "$TMP/out" && ok "both families classified match" || { bad "not classified match"; sed -n '1,20p' "$TMP/out"; }
grep -q 'safe to apply' "$TMP/out" && ok "says it is safe to apply" || bad "missing the safe-to-apply verdict"

sect "2. AURRAL RULES PRESENT -- must be AURRAL-ONLY (exit 3), not drift, not match"
ruleset 999999 "$AURRAL_RULES" > "$TMP/live4"
ruleset 888888 '-A INPUT -i aurral0 -j DROP' > "$TMP/live6"
rc="$(run "$TMP/backup4" "$TMP/live4" "$TMP/backup6" "$TMP/live6")"
[[ "$rc" == 3 ]] && ok "Aurral-only difference => exit 3" || bad "Aurral-only gave exit $rc, expected 3"
grep -q 'AURRAL-ONLY' "$TMP/out" && ok "reports AURRAL-ONLY" || bad "did not report AURRAL-ONLY"
grep -q 'DRIFT' "$TMP/out" && bad "wrongly reported DRIFT for Aurral's own rules" || ok "did not call Aurral's rules drift"

sect "3. A PRODUCTION RULE REMOVED -- must be DRIFT (exit 1). The case that matters most."
ruleset 999999 > "$TMP/live4"; sed -i '/-A ts-input -i lo -j ACCEPT/d' "$TMP/live4"
ruleset 888888 > "$TMP/live6"
rc="$(run "$TMP/backup4" "$TMP/live4" "$TMP/backup6" "$TMP/live6")"
[[ "$rc" == 1 ]] && ok "removed production rule => exit 1" || bad "removal gave exit $rc, expected 1"
grep -q 'ts-input -i lo' "$TMP/out" && ok "NAMES the removed rule" || bad "did not name the removed rule"

sect "4. A NON-AURRAL RULE ADDED -- must be DRIFT (exit 1)"
ruleset 999999 '-A INPUT -s 203.0.113.7/32 -j ACCEPT' > "$TMP/live4"
ruleset 888888 > "$TMP/live6"
rc="$(run "$TMP/backup4" "$TMP/live4" "$TMP/backup6" "$TMP/live6")"
[[ "$rc" == 1 ]] && ok "foreign addition => exit 1" || bad "foreign addition gave exit $rc, expected 1"
grep -q '203.0.113.7' "$TMP/out" && ok "NAMES the foreign rule" || bad "did not name the foreign rule"

sect "5. WEAKEST VERDICT GOVERNS -- v4 clean, v6 drifted => exit 1"
ruleset 999999 > "$TMP/live4"
ruleset 888888 > "$TMP/live6"; sed -i '/-A ts-input -i lo -j ACCEPT/d' "$TMP/live6"
rc="$(run "$TMP/backup4" "$TMP/live4" "$TMP/backup6" "$TMP/live6")"
[[ "$rc" == 1 ]] && ok "a clean v4 cannot mask a drifted v6" || bad "weakest verdict not applied: exit $rc"

sect "6. CANNOT ANSWER is neither verdict (exit 2)"
ruleset 999999 > "$TMP/live4"; ruleset 888888 > "$TMP/live6"
rc="$(run "$TMP/nonexistent" "$TMP/live4" "$TMP/backup6" "$TMP/live6")"
[[ "$rc" == 2 ]] && ok "missing backup => exit 2" || bad "missing backup gave exit $rc, expected 2"
: > "$TMP/empty"
rc="$(run "$TMP/empty" "$TMP/live4" "$TMP/backup6" "$TMP/live6")"
[[ "$rc" == 2 ]] && ok "EMPTY backup => exit 2 (not a pass)" || bad "empty backup gave exit $rc, expected 2"
grep -q 'do not treat this as a pass' "$TMP/out" && ok "says it is not a pass" || bad "missing the not-a-pass statement"

sect "7. MUTATION: remove the counter normalisation -- section 1 must break"
MUT="$TMP/preflight-mutant.sh"
cp "$PF" "$MUT"
python3 - "$MUT" <<'PY'
import sys
p = sys.argv[1]
s = open(p).read()
old = "         -e 's/^(:[A-Za-z0-9_.+-]+ (ACCEPT|DROP|REJECT|QUEUE|RETURN|-)) \\[[0-9]+:[0-9]+\\]$/\\1 [0:0]/'"
assert s.count(old) == 1, f"anchor matched {s.count(old)} times"
open(p, "w").write(s.replace(old, "         -e 's/^$//'"))
PY
if [[ $? -ne 0 ]]; then bad "7: the mutation did not apply"; else
  ruleset 999999 > "$TMP/live4"; ruleset 888888 > "$TMP/live6"
  AURRAL_PREFLIGHT_V4_LIVE="$TMP/live4" AURRAL_PREFLIGHT_V6_LIVE="$TMP/live6" \
    bash "$MUT" "$TMP/backup4" "$TMP/backup6" >"$TMP/mout" 2>&1; mrc=$?
  [[ "$mrc" == 1 ]] && ok "without normalisation a pristine ruleset reads as DRIFT (exit $mrc) -- the original defect" \
                     || bad "mutant gave exit $mrc; the normalisation is not what makes section 1 pass"
  grep -q 'DRIFT' "$TMP/mout" && ok "mutant prints the false DRIFT" || bad "mutant did not print DRIFT"
fi

sect "8. SAME RULES, DIFFERENT ORDER -- must be ORDER-ONLY (exit 4), not DRIFT"
# Measured in production 2026-11-25: recreating the stack made Docker re-emit
# its per-container PREROUTING guards in a different order, and the comparison
# reported 9 additions and 9 removals that were the SAME nine rules -- every IP
# belonging to a live container. Reported as DRIFT it reads as a lost
# production rule, which is the one thing this check exists to find.
GUARDS_A='-A PREROUTING -d 198.51.100.3/32 ! -i br-x -j DROP
-A PREROUTING -d 198.51.100.6/32 ! -i br-y -j DROP
-A PREROUTING -d 198.51.100.9/32 ! -i br-y -j DROP'
GUARDS_B='-A PREROUTING -d 198.51.100.9/32 ! -i br-y -j DROP
-A PREROUTING -d 198.51.100.3/32 ! -i br-x -j DROP
-A PREROUTING -d 198.51.100.6/32 ! -i br-y -j DROP'
ruleset 1000 "$GUARDS_A" > "$TMP/ob4"; ruleset 1000 "$GUARDS_B" > "$TMP/ol4"
ruleset 1000 > "$TMP/ob6"; ruleset 1000 > "$TMP/ol6"
rc="$(run "$TMP/ob4" "$TMP/ol4" "$TMP/ob6" "$TMP/ol6")"
[[ "$rc" == 4 ]] && ok "a reordering is ORDER-ONLY (exit 4)" || bad "reordering gave exit $rc, expected 4"
grep -q 'ORDER-ONLY' "$TMP/out" && ok "it says ORDER-ONLY" || bad "missing the ORDER-ONLY verdict"
grep -q 'No production rule was added or removed' "$TMP/out" \
  && ok "it states nothing was added or removed" || bad "missing the nothing-added statement"
grep -q 'PREROUTING' "$TMP/out" && ok "it still PRINTS the rules rather than hiding them" \
                                || bad "the rules were not shown"

sect "9. the verdict is CLEAN on stdout -- this function's stdout IS its return value"
# preflight.sh says so in its own header. Both the DRIFT and ORDER-ONLY branches
# printed their rule listing to stdout, so the rules were captured INTO the
# verdict: production showed "== verdict: v4=      --A PREROUTING ..." with the
# word drift buried mid-line. The glob in the case statement still matched, so
# the exit status was right and the report was mangled.
AURRAL_PREFLIGHT_V4_LIVE="$TMP/ol4" AURRAL_PREFLIGHT_V6_LIVE="$TMP/ol6" \
  bash "$PF" "$TMP/ob4" "$TMP/ob6" >"$TMP/sout" 2>/dev/null
vline="$(grep '^== verdict' "$TMP/sout" || true)"
[[ "$vline" == "== verdict: v4=order-only v6=match" ]] \
  && ok "verdict line is exactly the two words: $vline" \
  || bad "verdict line is contaminated: $vline"
grep -q 'PREROUTING' "$TMP/sout" && bad "rule text leaked onto stdout" \
                                 || ok "no rule text on stdout"

sect "10. ORDER-ONLY must not MASK a real loss -- a removal alongside a shuffle is DRIFT"
# If it did, the benign case would become a hiding place for the dangerous one.
GUARDS_C='-A PREROUTING -d 198.51.100.9/32 ! -i br-y -j DROP
-A PREROUTING -d 198.51.100.3/32 ! -i br-x -j DROP'
ruleset 1000 "$GUARDS_C" > "$TMP/ol4b"
rc="$(run "$TMP/ob4" "$TMP/ol4b" "$TMP/ob6" "$TMP/ol6")"
[[ "$rc" == 1 ]] && ok "shuffle PLUS a removal is still DRIFT (exit 1)" \
                 || bad "a shuffle hiding a removal gave exit $rc, expected 1"

sect "11. MUTATION: make the set comparison always true -- a real loss must read ORDER-ONLY"
MUT2="$TMP/preflight-mutant2.sh"
cp "$PF" "$MUT2"
python3 - "$MUT2" <<'PY2'
import sys
p = sys.argv[1]
s = open(p).read()
old = 'if (( o_add > 0 && o_add == o_rem )) && cmp -s "$TMP/$family.oadd" "$TMP/$family.orem"; then'
assert s.count(old) == 1, f"anchor matched {s.count(old)} times"
new = 'if (( o_add > 0 )); then'
open(p, "w").write(s.replace(old, new))
PY2
if [[ $? -ne 0 ]]; then bad "11: the mutation did not apply"; else
  # The fixture must produce the HARM, not merely reach the mutated line. A pure
  # removal has o_add == 0, so even the weakened condition refuses it -- the
  # first version of this fixture did that and the mutant "survived" for the
  # wrong reason. A rule SWAPPED for a different one gives o_add == o_rem == 1
  # with DIFFERENT sets, which is exactly what the comparison distinguishes.
  GUARDS_SWAP='-A PREROUTING -d 198.51.100.3/32 ! -i br-x -j DROP
-A PREROUTING -d 198.51.100.6/32 ! -i br-y -j DROP
-A PREROUTING -d 203.0.113.7/32 ! -i br-y -j DROP'
  ruleset 1000 "$GUARDS_A"    > "$TMP/mb4"
  ruleset 1000 "$GUARDS_SWAP" > "$TMP/ml4"
  # The REAL code must call that DRIFT, or the mutation proves nothing.
  rc="$(run "$TMP/mb4" "$TMP/ml4" "$TMP/ob6" "$TMP/ol6")"
  [[ "$rc" == 1 ]] && ok "a SWAPPED rule is DRIFT in the real code (exit 1)" \
                   || bad "the real code gave exit $rc for a swapped rule, expected 1"
  AURRAL_PREFLIGHT_V4_LIVE="$TMP/ml4" AURRAL_PREFLIGHT_V6_LIVE="$TMP/ol6" \
    bash "$MUT2" "$TMP/mb4" "$TMP/ob6" >"$TMP/m2out" 2>&1; m2rc=$?
  [[ "$m2rc" == 4 ]] && ok "the mutant calls a REMOVED rule order-only (exit $m2rc) -- the comparison is what prevents it" \
                      || bad "mutant gave exit $m2rc; the set comparison is not what distinguishes the two"
fi

printf '\n%s checks, %s failures\n' "$n" "$fails"
[[ "$fails" -eq 0 ]] || exit 1
